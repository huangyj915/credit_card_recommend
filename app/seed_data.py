def ensure_seed_data(db_path: Optional[Path] = None) -> int:
    """Populate database with reference cards if empty. Returns total card count."""
    if count_cards(db_path) == 0:
        for card in SEED_CARDS:
            upsert_card(card, db_path)
    return count_cards(db_path)
